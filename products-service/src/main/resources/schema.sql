CREATE TABLE IF NOT EXISTS product_types
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_type_id VARCHAR(36) NOT NULL UNIQUE,
    type_name       TEXT
);

CREATE TABLE IF NOT EXISTS product_ratings
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  VARCHAR(36) NOT NULL,
    customer_id VARCHAR(36) NOT NULL,
    rating      SMALLINT,
    review      TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS review_settings
(
    id                BIGINT PRIMARY KEY,
    edit_period_hours INTEGER NOT NULL
);

INSERT INTO review_settings (id, edit_period_hours)
values (1, 48)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS review_likes
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         VARCHAR(36) NOT NULL,
    review_customer_id VARCHAR(36) NOT NULL,
    liking_customer_id VARCHAR(36) NOT NULL,
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_review_like UNIQUE (product_id, review_customer_id, liking_customer_id)
);

CREATE TABLE IF NOT EXISTS product_bundles
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id            VARCHAR(36) NOT NULL UNIQUE,
    bundle_name          TEXT,
    bundle_description   TEXT,
    /* TODO: in the future use a seperate table to store product bundles products */
    product_ids          TEXT[],
    original_total_price DOUBLE PRECISION,
    bundle_price         DOUBLE PRECISION
);

